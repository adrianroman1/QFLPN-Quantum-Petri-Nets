"""Generate the existing P1 mathematical and numerical reports.

The final MANIFEST.txt and SHA256SUMS.txt are intentionally generated by
P1/tools/compute_checksums.py after this script and all later evidence writers
have completed. This avoids a stale inventory that omits the final report.
"""
from __future__ import annotations

import csv
import json
import platform
import sys
from pathlib import Path

import numpy as np
import scipy

ROOT = Path(__file__).resolve().parents[2]
P1 = ROOT / "P1"
OUT = P1 / "reports"
OUT.mkdir(parents=True, exist_ok=True)
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from P1.code.qflpn_reference import (
    fuzzy_to_angle, reference_state, density_matrix,
    positive_semidefinite_residual,
)
from P1.code.qflpn_transition_operator import (
    ry, c3x, qflpn_transition_operator, validate_unitarity,
)
from P1.tests.independent_reference import (
    independent_global_operator, independent_density_evolution,
)
from P1.tools.constants import NUMERICAL_TOLERANCE


def dump(name: str, data: dict) -> None:
    (OUT / name).write_text(
        json.dumps(data, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )


def main() -> None:
    dump("environment_report.json", {
        "python": platform.python_version(), "platform": platform.platform(),
        "numpy": np.__version__, "scipy": scipy.__version__,
        "status": "OBSERVED_AT_GENERATION",
    })
    dump("reference_specification_report.json", {
        "qubits": 4, "dimension": 16,
        "basis_order": "big-endian lexicographic computational basis |0000> ... |1111>",
        "dtype": "complex128", "status": "DECLARED_SPECIFICATION",
    })
    with (OUT / "activation_mapping_results.csv").open("w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow(["mu", "theta_rad", "sin2_theta_over_2", "absolute_error"])
        for mu in [0, .25, .5, .75, 1]:
            theta = fuzzy_to_angle(mu)
            actual = float(np.sin(theta / 2) ** 2)
            writer.writerow([mu, theta, actual, abs(actual - mu)])

    angles = [-2.3, -.1, 0, .7, np.pi]
    ry_errors = [float(np.linalg.norm(
        ry(t) - np.array([[np.cos(t/2), -np.sin(t/2)],
                          [np.sin(t/2), np.cos(t/2)]])
    )) for t in angles]
    dump("ry_validation_report.json", {
        "angles": angles, "frobenius_errors": ry_errors,
        "max_error": max(ry_errors),
    })

    state = reference_state([.2, .4, .6, .8])
    dump("state_preparation_report.json", {
        "dimension": int(state.size), "norm": float(np.linalg.norm(state)),
        "normalization_error": abs(float(np.linalg.norm(state)) - 1.0),
    })
    probabilities = np.abs(state) ** 2
    with (OUT / "probability_validation.csv").open("w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow(["basis_index", "basis_label", "probability"])
        for index, probability in enumerate(probabilities):
            writer.writerow([index, format(index, "04b"), float(probability)])

    gate = c3x()
    with (OUT / "c3x_truth_table.csv").open("w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow(["input_basis", "output_basis", "expected_output", "correct"])
        for index in range(16):
            output = int(np.argmax(np.abs(gate[:, index])))
            expected = index ^ 1 if (index & 14) == 14 else index
            writer.writerow([format(index, "04b"), format(output, "04b"),
                             format(expected, "04b"), output == expected])

    operator = qflpn_transition_operator()
    dump("global_operator_report.json", {
        "shape": list(operator.shape),
        "unitarity_residual": validate_unitarity(operator, tol=NUMERICAL_TOLERANCE),
    })
    rho = density_matrix(state)
    dump("density_validation_report.json", {
        "trace_real": float(np.trace(rho).real),
        "trace_imag": float(np.trace(rho).imag),
        "hermiticity_residual": float(np.linalg.norm(rho-rho.conj().T)),
        "psd_residual": positive_semidefinite_residual(rho, tol=NUMERICAL_TOLERANCE),
    })
    evolved = operator @ rho @ operator.conj().T
    dump("unitary_evolution_report.json", {
        "trace_real": float(np.trace(evolved).real),
        "trace_imag": float(np.trace(evolved).imag),
        "hermiticity_residual": float(np.linalg.norm(evolved-evolved.conj().T)),
        "psd_residual": positive_semidefinite_residual(evolved, tol=NUMERICAL_TOLERANCE),
    })

    u1 = np.kron(ry(.2), np.eye(2))
    u2 = np.kron(np.eye(2), ry(-.4))
    u3 = np.kron(np.array([[0, 1], [1, 0]], complex), np.eye(2))
    composed = u3 @ u2 @ u1
    dump("sequential_composition_report.json", {
        "order": "U3 @ U2 @ U1", "shape": list(composed.shape),
        "unitarity_residual": validate_unitarity(composed, tol=NUMERICAL_TOLERANCE),
    })
    dump("execution_contract_report.json", {
        "sequence": ["membership validation", "theta encoding", "RY/local operator",
                     "C3X", "density evolution", "probability observation"],
        "status": "NUMERICAL_DEMONSTRATOR_CONTRACT_ONLY",
        "full_Petri_net_semantics_proven": False,
    })

    bad_values = []
    for bad in [float("nan"), float("inf"), -float("inf")]:
        for label, function, argument in [
            ("PSD", positive_semidefinite_residual,
             np.array([[bad, 0], [0, 1]], complex)),
            ("unitarity", validate_unitarity,
             np.array([[bad, 0], [0, 1]], complex)),
        ]:
            try:
                function(argument, tol=NUMERICAL_TOLERANCE)
                rejected = False
            except ValueError:
                rejected = True
            bad_values.append({"check": label, "input": str(bad), "rejected": rejected})
    dump("robustness_report.json", {
        "nonfinite_cases": bad_values,
        "all_rejected": all(item["rejected"] for item in bad_values),
    })

    independent = independent_global_operator([.85, .90, .45, .70])
    production = qflpn_transition_operator([.85, .90, .45, .70])
    independent_rho = independent_density_evolution(independent, state)
    production_rho = production @ rho @ production.conj().T
    dump("independent_validation_report.json", {
        "operator_frobenius_difference": float(np.linalg.norm(independent-production)),
        "evolved_density_frobenius_difference": float(np.linalg.norm(independent_rho-production_rho)),
        "independent_code_imports_production": False,
    })

    # MANIFEST.txt and SHA256SUMS.txt are generated in the final CI stage only.
    dump("artifact_validation_report.json", {
        "status": "ARTIFACTS_GENERATED; FINAL_INVENTORY_PENDING",
        "manifest_sha256_generated_by": "P1/tools/compute_checksums.py",
        "pdf_tex_alignment_checked": False,
    })


if __name__ == "__main__":
    main()
