function qflpn_scaling_benchmark()

    clc;

    % ============================================================
    % QFLPN SCALING BENCHMARK
    %
    % Qubits:
    %       q = 4 ... 17
    %
    % States:
    %       N = 2^q
    %
    % The same QFLPN transition operator is scaled with q.
    %
    % U = I_(2^(q-1)) kron RY(theta)
    %
    % theta = 2 asin(sqrt(mu))
    %
    % ============================================================

    min_qubits = 4;
    max_qubits = 17;

    mu = 0.70;

    warmup_repetitions = 20;
    benchmark_repetitions = 1000;

    target_ms = 15.0;
    numerical_tolerance = 1.0e-12;

    theta = ...
        2.0 * asin(sqrt(mu));

    c = cos(theta);
    s = sin(theta);

    output_directory = 'results';

    if exist(output_directory, 'dir') ~= 7
        mkdir(output_directory);
    end

    output_file = fullfile( ...
        output_directory, ...
        'qflpn_scaling_matlab.csv');

    fid = fopen( ...
        output_file, ...
        'w');

    if fid == -1
        error( ...
            'Cannot open output file: %s', ...
            output_file);
    end

    fprintf( ...
        fid, ...
        ['language,qubits,states,nnz,mu,' ...
         'warmup,repetitions,construction_ms,' ...
         'mean_ms,median_ms,min_ms,max_ms,' ...
         'maximum_error,input_norm,output_norm,' ...
         'norm_error,target_ms,numerical_status,' ...
         'timing_status\n']);

    fprintf( ...
        'QFLPN scaling benchmark\n');

    fprintf( ...
        'Qubits: %d ... %d\n', ...
        min_qubits, ...
        max_qubits);

    fprintf( ...
        'States: N = 2^q\n');

    fprintf( ...
        'mu = %.12f\n', ...
        mu);

    fprintf( ...
        'Warmup: %d\n', ...
        warmup_repetitions);

    fprintf( ...
        'Repetitions: %d\n', ...
        benchmark_repetitions);

    fprintf( ...
        'Target: %.3f ms\n\n', ...
        target_ms);

    for q = min_qubits:max_qubits

        states = 2^q;

        fprintf( ...
            'Running q=%d, N=%d\n', ...
            q, ...
            states);

        % --------------------------------------------------------
        % Deterministic initial state
        % --------------------------------------------------------

        index = ...
            (0:(states - 1))';

        x = ...
            sin(index) ...
            + ...
            0.5 .* ...
            cos(0.37 .* index);

        input_norm = ...
            norm(x, 2);

        if input_norm == 0

            fclose(fid);

            error( ...
                'Initial state has zero norm.');

        end

        x = ...
            x ./ input_norm;

        % --------------------------------------------------------
        % Sparse operator construction
        % --------------------------------------------------------

        number_of_blocks = ...
            states / 2;

        rows = ...
            zeros( ...
                4 * number_of_blocks, ...
                1);

        cols = ...
            zeros( ...
                4 * number_of_blocks, ...
                1);

        values = ...
            zeros( ...
                4 * number_of_blocks, ...
                1);

        position = 1;

        for k = 1:number_of_blocks

            i = 2 * k - 1;
            j = 2 * k;

            rows(position) = i;
            cols(position) = i;
            values(position) = c;
            position = position + 1;

            rows(position) = i;
            cols(position) = j;
            values(position) = -s;
            position = position + 1;

            rows(position) = j;
            cols(position) = i;
            values(position) = s;
            position = position + 1;

            rows(position) = j;
            cols(position) = j;
            values(position) = c;
            position = position + 1;

        end

        rows = ...
            rows(1:position-1);

        cols = ...
            cols(1:position-1);

        values = ...
            values(1:position-1);

        % --------------------------------------------------------
        % Construction timing
        % --------------------------------------------------------

        construction_start = tic;

        A = sparse( ...
            rows, ...
            cols, ...
            values, ...
            states, ...
            states);

        construction_ms = ...
            toc(construction_start) * 1000.0;

        nnz_value = nnz(A);

        % --------------------------------------------------------
        % Independent analytical reference
        % --------------------------------------------------------

        y_reference = ...
            zeros(states, 1);

        for k = 1:number_of_blocks

            i = 2 * k - 1;
            j = 2 * k;

            y_reference(i) = ...
                c * x(i) ...
                - ...
                s * x(j);

            y_reference(j) = ...
                s * x(i) ...
                + ...
                c * x(j);

        end

        % --------------------------------------------------------
        % Warm-up
        % --------------------------------------------------------

        y = ...
            zeros(states, 1);

        for r = 1:warmup_repetitions

            y = A * x;

        end

        % --------------------------------------------------------
        % Timing
        % --------------------------------------------------------

        times_ms = ...
            zeros( ...
                benchmark_repetitions, ...
                1);

        for r = 1:benchmark_repetitions

            start_time = tic;

            y = A * x;

            times_ms(r) = ...
                toc(start_time) ...
                * ...
                1000.0;

        end

        % --------------------------------------------------------
        % Numerical validation
        % --------------------------------------------------------

        maximum_error = ...
            max( ...
                abs( ...
                    y - ...
                    y_reference));

        output_norm = ...
            norm(y, 2);

        norm_error = ...
            abs( ...
                output_norm ...
                - ...
                input_norm);

        numerical_status = ...
            'FAIL';

        if ...
            maximum_error <= numerical_tolerance ...
            && ...
            norm_error <= numerical_tolerance

            numerical_status = ...
                'PASS';

        end

        % --------------------------------------------------------
        % Timing statistics
        % --------------------------------------------------------

        mean_ms = ...
            mean(times_ms);

        sorted_times = ...
            sort(times_ms);

        left = ...
            benchmark_repetitions / 2;

        right = ...
            left + 1;

        median_ms = ...
            ( ...
                sorted_times(left) ...
                + ...
                sorted_times(right) ...
            ) / 2.0;

        min_ms = ...
            min(times_ms);

        max_ms = ...
            max(times_ms);

        timing_status = ...
            'FAIL';

        if mean_ms <= target_ms
            timing_status = ...
                'PASS';
        end

        % --------------------------------------------------------
        % Console output
        % --------------------------------------------------------

        fprintf( ...
            '  States: %d\n', ...
            states);

        fprintf( ...
            '  NNZ: %d\n', ...
            nnz_value);

        fprintf( ...
            '  Construction: %.6f ms\n', ...
            construction_ms);

        fprintf( ...
            '  Mean: %.6f ms\n', ...
            mean_ms);

        fprintf( ...
            '  Median: %.6f ms\n', ...
            median_ms);

        fprintf( ...
            '  Maximum error: %.3e\n', ...
            maximum_error);

        fprintf( ...
            '  Norm error: %.3e\n', ...
            norm_error);

        fprintf( ...
            '  Numerical: %s\n', ...
            numerical_status);

        fprintf( ...
            '  Timing: %s\n\n', ...
            timing_status);

        % --------------------------------------------------------
        % CSV
        % --------------------------------------------------------

        fprintf( ...
            fid, ...
            ['MATLAB,%d,%d,%d,%.12f,%d,%d,' ...
             '%.12f,%.12f,%.12f,%.12f,%.12f,' ...
             '%.12e,%.12e,%.12e,%.12e,%.12f,%s,%s\n'], ...
            q, ...
            states, ...
            nnz_value, ...
            mu, ...
            warmup_repetitions, ...
            benchmark_repetitions, ...
            construction_ms, ...
            mean_ms, ...
            median_ms, ...
            min_ms, ...
            max_ms, ...
            maximum_error, ...
            input_norm, ...
            output_norm, ...
            norm_error, ...
            target_ms, ...
            numerical_status, ...
            timing_status);

    end

    fclose(fid);

    fprintf( ...
        'Benchmark completed.\n');

    fprintf( ...
        'Results saved to:\n');

    fprintf( ...
        '%s\n', ...
        output_file);

end