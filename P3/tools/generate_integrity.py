#!/usr/bin/env python3
"""Generate and verify P3/MANIFEST.txt and P3/SHA256SUMS.txt.

From repository root:
    python3 P3/tools/generate_integrity.py --write
    python3 P3/tools/generate_integrity.py --check

The manifest inventories files below P3, excluding the two generated
outputs and transient build/cache directories. SHA256SUMS.txt includes
the generated manifest itself.
"""

from __future__ import annotations

import argparse
import hashlib
import os
import sys
import tempfile
from pathlib import Path

P3_ROOT = Path(__file__).resolve().parents[1]

GENERATED_FILES = {
    "MANIFEST.txt",
    "SHA256SUMS.txt",
}

EXCLUDED_DIRECTORIES = {
    ".git",
    "target",
    "__pycache__",
    ".pytest_cache",
    ".mypy_cache",
}


def calculate_sha256(path: Path) -> str:
    digest = hashlib.sha256()

    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)

    return digest.hexdigest()


def collect_files(root: Path) -> list[Path]:
    collected: list[Path] = []

    for current, directories, filenames in os.walk(
        root,
        followlinks=False,
    ):
        current_path = Path(current)

        directories[:] = sorted(
            directory
            for directory in directories
            if directory not in EXCLUDED_DIRECTORIES
            and not (current_path / directory).is_symlink()
        )

        for filename in sorted(filenames):
            path = current_path / filename

            if filename in GENERATED_FILES:
                continue

            if path.is_symlink():
                continue

            if not path.is_file():
                continue

            collected.append(path)

    return sorted(
        collected,
        key=lambda path: path.relative_to(root).as_posix(),
    )


def build_manifest(
    root: Path,
    files: list[Path],
) -> bytes:
    lines = [
        "# QFLPN P3 — generated file manifest",
        "# Generated automatically by P3/tools/generate_integrity.py",
        "# Do not edit this file manually.",
        f"# Inventoried files: {len(files)}",
        "",
    ]

    for path in files:
        lines.append(path.relative_to(root).as_posix())

    return ("\n".join(lines) + "\n").encode("utf-8")


def build_checksums(
    root: Path,
    files: list[Path],
    manifest: bytes,
) -> bytes:
    entries: list[tuple[str, str]] = []

    for path in files:
        relative_path = path.relative_to(root).as_posix()
        entries.append(
            (relative_path, calculate_sha256(path))
        )

    entries.append(
        (
            "MANIFEST.txt",
            hashlib.sha256(manifest).hexdigest(),
        )
    )

    entries.sort(key=lambda entry: entry[0])

    content = "".join(
        f"{digest}  {filename}\n"
        for filename, digest in entries
    )

    return content.encode("utf-8")


def atomic_write(path: Path, content: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)

    descriptor, temporary_name = tempfile.mkstemp(
        prefix=path.name + ".",
        dir=path.parent,
    )

    try:
        with os.fdopen(descriptor, "wb") as stream:
            stream.write(content)
            stream.flush()
            os.fsync(stream.fileno())

        os.replace(temporary_name, path)

    except BaseException:
        try:
            os.unlink(temporary_name)
        except FileNotFoundError:
            pass
        raise


def generate(root: Path, write: bool) -> bool:
    root = root.resolve()

    if not root.is_dir():
        raise ValueError(f"P3 directory does not exist: {root}")

    files = collect_files(root)

    manifest = build_manifest(root, files)
    checksums = build_checksums(root, files, manifest)

    outputs = {
        root / "MANIFEST.txt": manifest,
        root / "SHA256SUMS.txt": checksums,
    }

    if write:
        for path, content in outputs.items():
            atomic_write(path, content)

        print(
            "[PASS] Generated MANIFEST.txt and SHA256SUMS.txt "
            f"({len(files)} inventoried files)"
        )
        return True

    stale_files = []

    for path, expected_content in outputs.items():
        if not path.is_file():
            stale_files.append(path.name)
            continue

        if path.read_bytes() != expected_content:
            stale_files.append(path.name)

    if stale_files:
        print(
            "[FAIL] Missing or stale generated files: "
            + ", ".join(stale_files),
            file=sys.stderr,
        )
        print(
            "Run: python3 P3/tools/generate_integrity.py --write",
            file=sys.stderr,
        )
        return False

    print(
        "[PASS] Manifest and SHA-256 verified "
        f"({len(files)} inventoried files)"
    )
    return True


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Generate or verify P3 integrity files."
    )

    mode = parser.add_mutually_exclusive_group(required=True)

    mode.add_argument(
        "--write",
        action="store_true",
        help="regenerate MANIFEST.txt and SHA256SUMS.txt",
    )

    mode.add_argument(
        "--check",
        action="store_true",
        help="verify committed integrity files without modifying them",
    )

    parser.add_argument(
        "--root",
        type=Path,
        default=P3_ROOT,
        help="P3 directory; primarily intended for tests",
    )

    arguments = parser.parse_args()

    try:
        success = generate(
            arguments.root,
            write=arguments.write,
        )
        return 0 if success else 1

    except (OSError, ValueError) as error:
        print(f"[FAIL] {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
