#!/usr/bin/env python3
"""Independently verify P3/MANIFEST.txt and P3/SHA256SUMS.txt.

The format is deliberately identical to the one generated by
P3/tools/compute_checksums.py:

- MANIFEST.txt contains sorted repository-relative P3/... paths.
- SHA256SUMS.txt contains SHA-256 entries for exactly those paths.
- Neither generated integrity file is included in its own inventory.
- Symlinks, cache/build directories, and Python bytecode are excluded.

This verifier reconstructs the inventory independently. It does not
import or call the checksum generator.
"""

from __future__ import annotations

import argparse
import hashlib
import os
import re
import sys
from pathlib import Path, PurePosixPath
from typing import Any


ROOT = Path(__file__).resolve().parents[2]

MANIFEST_RELATIVE = "P3/MANIFEST.txt"
CHECKSUMS_RELATIVE = "P3/SHA256SUMS.txt"

GENERATED_NAMES = {
    "MANIFEST.txt",
    "SHA256SUMS.txt",
}

EXCLUDED_DIRS = {
    "target",
    "__pycache__",
    ".pytest_cache",
    ".mypy_cache",
    ".ruff_cache",
}

EXCLUDED_SUFFIXES = {
    ".pyc",
    ".pyo",
}

HEX64 = re.compile(r"^[0-9a-f]{64}$")
CHECKSUM_LINE = re.compile(r"^([0-9a-f]{64})  ([^\r\n]+)$")


class IntegrityError(RuntimeError):
    """Raised when P3 manifest or checksum integrity is invalid."""


def require(condition: bool, message: str) -> None:
    if not condition:
        raise IntegrityError(message)


def sha256_file(path: Path) -> str:
    """Calculate a file's SHA-256 digest without loading it all into RAM."""
    require(
        not path.is_symlink() and path.is_file(),
        f"unsafe or missing file: {path}",
    )

    digest = hashlib.sha256()

    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)

    return digest.hexdigest()


def validate_inventory_path(value: str) -> None:
    """Reject paths outside P3 and noncanonical or unsafe paths."""
    require(bool(value), "inventory path must not be empty")
    require("\\" not in value, f"backslash in inventory path: {value!r}")
    require(value.strip() == value, f"whitespace in inventory path: {value!r}")
    require(value.startswith("P3/"), f"path is outside P3/: {value!r}")

    path = PurePosixPath(value)

    require(
        not path.is_absolute()
        and ".." not in path.parts
        and "." not in path.parts
        and path.as_posix() == value,
        f"unsafe or noncanonical inventory path: {value!r}",
    )

    require(
        path.name not in GENERATED_NAMES,
        f"self-referential integrity path is forbidden: {value!r}",
    )


def independent_inventory(repository_root: Path) -> list[str]:
    """Rebuild the eligible P3 file inventory without using the generator."""
    repository_root = Path(repository_root).resolve()
    p3_root = repository_root / "P3"

    require(
        p3_root.is_dir() and not p3_root.is_symlink(),
        f"P3 directory is missing or unsafe: {p3_root}",
    )

    found: list[str] = []

    for current, directory_names, file_names in os.walk(
        p3_root,
        topdown=True,
        followlinks=False,
    ):
        current_path = Path(current)

        directory_names[:] = sorted(
            name
            for name in directory_names
            if name not in EXCLUDED_DIRS
            and not (current_path / name).is_symlink()
        )

        for name in sorted(file_names):
            path = current_path / name

            if name in GENERATED_NAMES:
                continue

            if path.suffix.lower() in EXCLUDED_SUFFIXES:
                continue

            if path.is_symlink() or not path.is_file():
                continue

            relative = path.relative_to(repository_root).as_posix()
            validate_inventory_path(relative)
            found.append(relative)

    found.sort()

    require(
        bool(found),
        "P3 filesystem inventory is empty",
    )
    require(
        len(found) == len(set(found)),
        "P3 filesystem inventory contains duplicate paths",
    )

    return found


def read_canonical_text(path: Path, label: str) -> str:
    """Read UTF-8/ASCII text and enforce LF final-newline formatting."""
    try:
        raw = path.read_bytes()
    except OSError as exc:
        raise IntegrityError(
            f"cannot read {label}: {exc}"
        ) from exc

    require(bool(raw), f"{label} is empty")
    require(raw.endswith(b"\n"), f"{label} has no final newline")
    require(b"\r" not in raw, f"{label} must use LF line endings")

    try:
        return raw.decode("ascii")
    except UnicodeDecodeError as exc:
        raise IntegrityError(
            f"{label} is not valid ASCII"
        ) from exc


def parse_manifest(path: Path) -> list[str]:
    """Parse the generator's canonical paths-only manifest."""
    content = read_canonical_text(path, "P3/MANIFEST.txt")
    entries = content[:-1].split("\n")

    require(
        bool(entries) and all(entries),
        "P3/MANIFEST.txt contains blank entries",
    )
    require(
        entries == sorted(entries),
        "P3/MANIFEST.txt entries are not sorted",
    )
    require(
        len(entries) == len(set(entries)),
        "P3/MANIFEST.txt contains duplicate paths",
    )

    for entry in entries:
        validate_inventory_path(entry)

    return entries


def parse_checksums(path: Path) -> dict[str, str]:
    """Parse canonical GNU-style SHA-256 records."""
    content = read_canonical_text(path, "P3/SHA256SUMS.txt")
    lines = content[:-1].split("\n")

    require(
        bool(lines) and all(lines),
        "P3/SHA256SUMS.txt contains blank entries",
    )

    result: dict[str, str] = {}

    for number, line in enumerate(lines, start=1):
        match = CHECKSUM_LINE.fullmatch(line)

        require(
            match is not None,
            f"malformed P3/SHA256SUMS.txt line {number}",
        )

        assert match is not None
        digest, relative = match.groups()

        require(
            HEX64.fullmatch(digest) is not None,
            f"invalid SHA-256 digest on line {number}",
        )

        validate_inventory_path(relative)

        require(
            relative not in result,
            f"duplicate checksum path: {relative}",
        )

        result[relative] = digest

    require(
        list(result) == sorted(result),
        "P3/SHA256SUMS.txt entries are not sorted",
    )

    return result


def verify(repository_root: Path) -> dict[str, Any]:
    """Verify manifest inventory and every declared file digest."""
    repository_root = Path(repository_root).resolve()

    require(
        repository_root.is_dir(),
        f"repository root does not exist: {repository_root}",
    )

    p3_root = repository_root / "P3"
    manifest_path = p3_root / "MANIFEST.txt"
    checksums_path = p3_root / "SHA256SUMS.txt"

    require(
        not p3_root.is_symlink(),
        "P3 directory must not be a symbolic link",
    )
    require(
        manifest_path.is_file() and not manifest_path.is_symlink(),
        "P3/MANIFEST.txt is missing or unsafe",
    )
    require(
        checksums_path.is_file() and not checksums_path.is_symlink(),
        "P3/SHA256SUMS.txt is missing or unsafe",
    )

    manifest = parse_manifest(manifest_path)
    actual_inventory = independent_inventory(repository_root)

    if manifest != actual_inventory:
        missing = sorted(set(actual_inventory) - set(manifest))
        extra = sorted(set(manifest) - set(actual_inventory))

        raise IntegrityError(
            "P3 manifest inventory mismatch; "
            f"missing={missing}; extra={extra}"
        )

    checksums = parse_checksums(checksums_path)

    manifest_set = set(manifest)
    checksum_set = set(checksums)

    require(
        checksum_set == manifest_set,
        (
            "P3 manifest/checksum path sets differ; "
            f"missing_checksums={sorted(manifest_set - checksum_set)}; "
            f"extra_checksums={sorted(checksum_set - manifest_set)}"
        ),
    )

    verified = 0

    for relative in manifest:
        path = repository_root / Path(*PurePosixPath(relative).parts)

        require(
            not path.is_symlink() and path.is_file(),
            f"manifest path is missing or unsafe: {relative}",
        )

        actual_digest = sha256_file(path)
        expected_digest = checksums[relative]

        require(
            actual_digest == expected_digest,
            (
                f"SHA-256 mismatch for {relative}: "
                f"expected {expected_digest}, got {actual_digest}"
            ),
        )

        verified += 1

    return {
        "validation": "PASS",
        "manifest_path": MANIFEST_RELATIVE,
        "checksums_path": CHECKSUMS_RELATIVE,
        "manifest_entries": len(manifest),
        "sha256_entries_verified": verified,
        "inventory_format": "repository-relative-P3-paths",
    }


def main() -> int:
    parser = argparse.ArgumentParser(
        description=(
            "Independently verify P3/MANIFEST.txt and "
            "P3/SHA256SUMS.txt generated by compute_checksums.py."
        )
    )

    parser.add_argument(
        "--root",
        type=Path,
        default=ROOT,
        help="repository root containing the P3 directory",
    )

    args = parser.parse_args()

    try:
        result = verify(args.root)

        print(
            "[PASS] Independent P3 integrity verification: "
            f"{result['manifest_entries']} manifest entries; "
            f"{result['sha256_entries_verified']} SHA-256 digests"
        )
        print(
            "P3_INDEPENDENT_INTEGRITY: PASS"
        )

        return 0

    except (OSError, IntegrityError, ValueError) as exc:
        print(
            f"[FAIL] Independent P3 integrity verification: {exc}",
            file=sys.stderr,
        )
        print(
            "P3_INDEPENDENT_INTEGRITY: FAIL",
            file=sys.stderr,
        )

        return 1


if __name__ == "__main__":
    raise SystemExit(main())
