class EvidenceError(RuntimeError):
    """Raised when P3 evidence is missing, inconsistent or unsafe."""


def require(condition: bool, message: str) -> None:
    if not condition:
        raise EvidenceError(message)


def regular_file(path: Path, label: str) -> None:
    require(
        not path.is_symlink(),
        f"Symlink detected for {label}: {path}",
    )
    require(
        path.is_file(),
        f"{label} is missing or is not a regular file: {path}",
    )


def read_text(
    path: Path,
    label: str,
    encoding: str = "utf-8",
) -> str:
    regular_file(path, label)

    try:
        return path.read_text(encoding=encoding)
    except (OSError, UnicodeError) as exc:
        raise EvidenceError(
            f"Cannot read {label}: {exc}"
        ) from exc


def read_json(path: Path, label: str) -> dict[str, Any]:
    content = read_text(path, label)

    try:
        value = json.loads(content)
    except json.JSONDecodeError as exc:
        raise EvidenceError(
            f"{label} is invalid JSON: {exc}"
        ) from exc

    require(
        isinstance(value, dict),
        f"{label} must be a JSON object",
    )

    return value


def finite(value: Any, label: str) -> float:
    require(
        not isinstance(value, bool),
        f"{label} must be numeric, not boolean",
    )

    try:
        result = float(value)
    except (TypeError, ValueError, OverflowError) as exc:
        raise EvidenceError(
            f"{label} must be numeric"
        ) from exc

    require(
        math.isfinite(result),
        f"{label} must be finite",
    )

    return result


def same_number(left: Any, right: Any, label: str) -> None:
    first = finite(left, label)
    second = finite(right, label)

    require(
        math.isclose(
            first,
            second,
            rel_tol=1e-8,
            abs_tol=1e-12,
        ),
        f"{label} mismatch: {first} != {second}",
    )


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()

    with path.open("rb") as stream:
        for block in iter(
            lambda: stream.read(1024 * 1024),
            b"",
        ):
            digest.update(block)

    return digest.hexdigest()


def safe_target(p3_root: Path, name: str) -> Path:
    """Resolve a checksum target without permitting traversal or symlinks."""

    require(
        isinstance(name, str) and bool(name),
        "Empty checksum path",
    )

    require(
        "\\" not in name,
        f"Backslash in checksum path: {name}",
    )

    relative = PurePosixPath(name)

    require(
        not relative.is_absolute(),
        f"Absolute checksum path: {name}",
    )

    require(
        all(
            part not in {"", ".", ".."}
            for part in relative.parts
        ),
        f"Unsafe checksum path: {name}",
    )

    root = p3_root.resolve()
    target = p3_root.joinpath(*relative.parts)
    resolved = target.resolve()

    require(
        resolved != root and root in resolved.parents,
        f"Checksum path escapes P3 root: {name}",
    )

    current = p3_root

    for part in relative.parts:
        current = current / part

        require(
            not current.is_symlink(),
            f"Symlink in checksum path: {name}",
        )

    regular_file(
        target,
        f"Checksum target {name}",
    )

    return target


def verify_checksums(
    p3_root: Path,
    checksum_file: Path,
    expected_paths: set[str],
) -> list[str]:
    """Verify an exact checksum inventory and every corresponding digest."""

    content = read_text(
        checksum_file,
        "SHA256SUMS.txt",
        encoding="ascii",
    )

    parsed: dict[str, str] = {}

    for number, line in enumerate(
        content.splitlines(),
        start=1,
    ):
        match = re.fullmatch(
            r"([0-9a-f]{64})  ([^\r\n]+)",
            line,
        )

        require(
            match is not None,
            f"Malformed checksum line {number}",
        )

        assert match is not None

        digest, name = match.groups()

        require(
            SHA256_RE.fullmatch(digest) is not None,
            f"Invalid SHA-256 digest on line {number}",
        )

        require(
            name not in parsed,
            f"Duplicate checksum entry: {name}",
        )

        parsed[name] = digest

    actual_paths = set(parsed)

    require(
        actual_paths == expected_paths,
        (
            "Checksum path set mismatch; "
            f"missing={sorted(expected_paths - actual_paths)}; "
            f"unexpected={sorted(actual_paths - expected_paths)}"
        ),
    )

    for name, expected_digest in parsed.items():
        target = safe_target(p3_root, name)
        actual_digest = sha256_file(target)

        require(
            actual_digest == expected_digest,
            f"SHA-256 mismatch: {name}",
        )

    return sorted(parsed)


def read_csv(
    path: Path,
    required: set[str],
) -> list[dict[str, str]]:
    """Read CSV evidence with strict structural checks."""

    regular_file(
        path,
        "Canonical benchmark CSV",
    )

    try:
        with path.open(
            "r",
            encoding="utf-8-sig",
            newline="",
        ) as stream:
            reader = csv.DictReader(
                stream,
                strict=True,
            )

            require(
                reader.fieldnames is not None,
                "CSV header is missing",
            )

            assert reader.fieldnames is not None

            require(
                len(reader.fieldnames)
                == len(set(reader.fieldnames)),
                "CSV contains duplicate column names",
            )

            missing = required - set(reader.fieldnames)

            require(
                not missing,
                f"CSV missing columns: {sorted(missing)}",
            )

            rows = []

            for number, row in enumerate(
                reader,
                start=1,
            ):
                require(
                    None not in row,
                    f"CSV row {number} has extra fields",
                )

                require(
                    all(value is not None for value in row.values()),
                    f"CSV row {number} has missing fields",
                )

                rows.append(row)

    except EvidenceError:
        raise
    except (OSError, UnicodeError, csv.Error) as exc:
        raise EvidenceError(
            f"Cannot read benchmark CSV: {exc}"
        ) from exc

    require(
        bool(rows),
        f"CSV contains no records: {path}",
    )

    return rows


def load_validator(path: Path, module_name: str) -> Any:
    """Load an authoritative validator from the checked-out P3 source."""

    regular_file(
        path,
        f"Authoritative validator {module_name}",
    )

    spec = importlib.util.spec_from_file_location(
        module_name,
        path,
    )

    require(
        spec is not None and spec.loader is not None,
        f"Cannot load authoritative validator: {path}",
    )

    assert spec is not None
    assert spec.loader is not None

    # Correct module construction: spec, not module_name.
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module

    try:
        spec.loader.exec_module(module)
    except Exception as exc:
        raise EvidenceError(
            f"Cannot initialize validator {module_name}: {exc}"
        ) from exc

    require(
        callable(getattr(module, "validate", None)),
        f"{module_name} does not expose validate()",
    )

    return module


def verify_execution_identity(
    path: Path,
    *,
    run_id: str,
    workflow_run_id: str,
    source_commit: str,
) -> dict[str, str]:
    """Verify the immutable identity file written by run_benchmark.sh."""

    content = read_text(
        path,
        "V2 execution identity",
    )

    identity: dict[str, str] = {}

    for number, line in enumerate(
        content.splitlines(),
        start=1,
    ):
        require(
            "=" in line,
            f"Malformed execution identity line {number}",
        )

        key, value = line.split("=", 1)

        require(
            key not in identity,
            f"Duplicate execution identity key: {key}",
        )

        require(
            bool(key) and bool(value),
            f"Empty execution identity field on line {number}",
        )

        identity[key] = value

    expected = {
        "P3_RUN_ID": run_id,
        "P3_WORKFLOW_RUN_ID": workflow_run_id,
        "P3_SOURCE_COMMIT": source_commit,
    }

    for key, value in expected.items():
        require(
            identity.get(key) == value,
            f"Execution identity mismatch: {key}",
        )

    require(
        identity.get("P3_V2_DIMENSION") is not None,
        "Execution identity is missing P3_V2_DIMENSION",
    )

    require(
        identity.get("P3_V3_DIMENSION") is not None,
        "Execution identity is missing P3_V3_DIMENSION",
    )

    for key in (
        "P3_V2_DIMENSION",
        "P3_V3_DIMENSION",
    ):
        require(
            re.fullmatch(r"[1-9][0-9]*", identity[key]) is not None,
            f"Invalid execution identity value: {key}",
        )

    return identity


def verify_v2(
    root: Path,
    run_id: str,
    workflow_run_id: str,
    source_commit: str,
) -> dict[str, Any]:
    """Validate all V2 CSV records and cross-check current-run evidence."""

    p3 = root / "P3"
    raw = p3 / "results" / "raw" / run_id

    csv_path = (
        p3
        / "benchmarks"
        / "benchmark_results_v2.csv"
    )

    rows = read_csv(
        csv_path,
        V2_REQUIRED,
    )

    matches = [
        row
        for row in rows
        if row.get("run_id") == run_id
    ]

    require(
        len(matches) == 1,
        f"V2 expected one row for RUN_ID={run_id}; got {len(matches)}",
    )

    row = matches[0]

    validator_path = (
        p3
        / "results"
        / "validate_benchmark.py"
    )

    validator = load_validator(
        validator_path,
        "p3_authoritative_v2_validator",
    )

    try:
        authoritative = validator.validate(csv_path)
    except Exception as exc:
        raise EvidenceError(
            f"Authoritative V2 validation failed: {exc}"
        ) from exc

    require(
        isinstance(authoritative, dict),
        "V2 validator returned an invalid result",
    )

    require(
        authoritative.get("schema") == "qflpn-benchmark-v2",
        "V2 validator returned an unexpected schema",
    )

    require(
        authoritative.get("validation") == "PASS",
        "Authoritative V2 validator did not PASS",
    )

    require(
        authoritative.get("all_records_valid") is True,
        "Authoritative V2 validator did not confirm all records",
    )

    validation_report_path = (
        raw / "validation-report.json"
    )

    validation_report = read_json(
        validation_report_path,
        "V2 run-specific validation report",
    )

    require(
        validation_report == authoritative,
        "V2 run-specific validation report differs from "
        "the authoritative validator result",
    )

    latest = authoritative.get("latest_record")

    require(
        isinstance(latest, dict),
        "V2 authoritative latest_record is missing",
    )

    require(
        latest.get("run_id") == run_id,
        "V2 authoritative report RUN_ID mismatch",
    )

    require(
        latest.get("run_id") == row.get("run_id"),
        "V2 CSV and validator RUN_ID mismatch",
    )

    for csv_key, report_key in (
        ("dimension", "dimension"),
        ("non_zero_count", "nnz"),
    ):
        try:
            csv_value = int(row[csv_key])
            report_value = int(latest[report_key])
        except (KeyError, TypeError, ValueError, OverflowError) as exc:
            raise EvidenceError(
                f"Invalid V2 identity field: {csv_key}"
            ) from exc

        require(
            csv_value == report_value,
            f"V2 CSV/report mismatch: {csv_key}",
        )

    require(
        row.get("benchmark_id") == latest.get("benchmark_id"),
        "V2 CSV/report benchmark_id mismatch",
    )

    for csv_key, report_key in (
        ("speedup", "speedup"),
        ("sequential_mean_ms", "sequential_mean_ms"),
        ("parallel_mean_ms", "parallel_mean_ms"),
        ("max_absolute_error", "max_error"),
    ):
        same_number(
            row.get(csv_key),
            latest.get(report_key),
            f"V2 {csv_key}",
        )

    java_report_path = (
        raw / "benchmark-report.json"
    )

    java_report = read_json(
        java_report_path,
        "V2 Java benchmark report",
    )

    require(
        java_report.get("run_id") == run_id,
        "V2 Java report RUN_ID mismatch",
    )

    require(
        java_report.get("dimension") == int(row["dimension"]),
        "V2 Java report dimension mismatch",
    )

    require(
        java_report.get("validation") == "PASS",
        "V2 Java report is not PASS",
    )

    text_path = raw / "benchmark-report.txt"
    text_content = read_text(
        text_path,
        "V2 Java text report",
    )

    require(
        f"RUN_ID={run_id}" in text_content,
        "V2 Java text report RUN_ID mismatch",
    )

    markdown_path = raw / "benchmark-report.md"
    markdown = read_text(
        markdown_path,
        "V2 run Markdown report",
    )

    require(
        run_id in markdown,
        "V2 run Markdown RUN_ID mismatch",
    )

    require(
        "Validation: **PASS**" in markdown,
        "V2 run Markdown is not PASS",
    )

    persistent_md_path = (
        p3 / "reports" / "benchmark-report.md"
    )

    persistent_md = read_text(
        persistent_md_path,
        "V2 persistent Markdown report",
    )

    require(
        run_id in persistent_md,
        "V2 persistent Markdown RUN_ID mismatch",
    )

    require(
        "Validation: **PASS**" in persistent_md,
        "V2 persistent Markdown is not PASS",
    )

    persistent_json_path = (
        p3 / "reports" / "validation-report.json"
    )

    persistent_json = read_json(
        persistent_json_path,
        "V2 persistent validation JSON",
    )

    require(
        persistent_json == authoritative,
        "V2 persistent validation JSON differs from "
        "the authoritative validator result",
    )

    identity = verify_execution_identity(
        raw / "execution-identity.txt",
        run_id=run_id,
        workflow_run_id=workflow_run_id,
        source_commit=source_commit,
    )

    require(
        int(identity["P3_V2_DIMENSION"]) == int(row["dimension"]),
        "V2 execution identity dimension mismatch",
    )

    expected_checksums = {
        item.format(run_id=run_id)
        for item in V2_RUN_CHECKSUMS
    }

    checksums = verify_checksums(
        p3,
        raw / "SHA256SUMS.txt",
        expected_checksums,
    )

    return {
        "validation": "PASS",
        "schema": "qflpn-benchmark-v2",
        "run_id": run_id,
        "dimension": int(row["dimension"]),
        "benchmark_id": row["benchmark_id"],
        "nnz": int(row["non_zero_count"]),
        "records": authoritative["records"],
        "verified_checksums": checksums,
        "execution_identity": "PASS",
        "authoritative_validator": "PASS",
    }


def verify_v3(
    root: Path,
    run_id: str,
    source_commit: str,
    workflow_run_id: str,
) -> dict[str, Any]:
    """Independently validate V3 records, provenance and persistent evidence."""

    p3 = root / "P3"

    csv_path = (
        p3
        / "benchmarks"
        / "benchmark_results_v3.csv"
    )

    rows = read_csv(
        csv_path,
        V3_REQUIRED,
    )

    matches = [
        row
        for row in rows
        if row.get("run_id") == run_id
    ]

    require(
        bool(matches),
        f"V3 has no rows for RUN_ID={run_id}",
    )

    commits = {
        row["commit_sha"]
        for row in matches
    }

    workflows = {
        row["workflow_run_id"]
        for row in matches
    }

    require(
        commits == {source_commit},
        "V3 CSV source commit mismatch",
    )

    require(
        workflows == {workflow_run_id},
        "V3 CSV workflow run ID mismatch",
    )

    validator_path = (
        p3
        / "results"
        / "validate_benchmark_v3.py"
    )

    validator = load_validator(
        validator_path,
        "p3_authoritative_v3_validator",
    )

    try:
        result = validator.validate(
            csv_path,
            run_id=run_id,
            workflow_run_id=workflow_run_id,
            commit_sha=source_commit,
        )
    except Exception as exc:
        raise EvidenceError(
            f"Authoritative V3 validation failed: {exc}"
        ) from exc

    require(
        isinstance(result, dict),
        "V3 validator returned an invalid result",
    )

    require(
        result.get("schema") == "qflpn-benchmark-v3-validation-v2",
        "V3 validator returned an unexpected schema",
    )

    require(
        result.get("validation") == "PASS",
        "V3 validator did not PASS",
    )

    require(
        result.get("all_records_valid") is True,
        "V3 validator did not confirm all records valid",
    )

    require(
        result.get("configuration_matrix_complete") is True,
        "V3 configuration matrix is incomplete",
    )

    require(
        result.get("run_id") == run_id,
        "V3 validator RUN_ID mismatch",
    )

    require(
        result.get("run_contract") in {
            "LEGACY_96",
            "AB_192",
        },
        "Unsupported V3 run contract",
    )

    require(
        result.get("workflow_run_id") == workflow_run_id,
        "V3 validator workflow run ID mismatch",
    )

    require(
        result.get("commit_sha") == source_commit,
        "V3 validator source commit mismatch",
    )

    report_path = (
        p3
        / "reports"
        / "benchmark-v3-validation.json"
    )

    report = read_json(
        report_path,
        "Persistent V3 validation report",
    )

    require(
        report.get("schema") == result["schema"],
        "V3 persistent report schema mismatch",
    )

    require(
        report.get("validation") == "PASS",
        "Persistent V3 report is not PASS",
    )

    require(
        report.get("run_id") == run_id,
        "Persistent V3 report RUN_ID mismatch",
    )

    require(
        report.get("commit_sha") == source_commit,
        "Persistent V3 report commit mismatch",
    )

    require(
        report.get("workflow_run_id") == workflow_run_id,
        "Persistent V3 report workflow run ID mismatch",
    )

    require(
        report.get("validated_records")
        == result.get("validated_records"),
        "Persistent V3 report record count mismatch",
    )

    require(
        report.get("run_contract")
        == result.get("run_contract"),
        "Persistent V3 report contract mismatch",
    )

    checksum_path = (
        p3
        / "reports"
        / "benchmark-v3-SHA256SUMS.txt"
    )

    verified = verify_checksums(
        p3,
        checksum_path,
        V3_RUN_CHECKSUMS,
    )

    return {
        "validation": "PASS",
        "schema": result["schema"],
        "run_id": run_id,
        "workflow_run_id": workflow_run_id,
        "source_commit": source_commit,
        "run_contract": result["run_contract"],
        "validated_records": result["validated_records"],
        "verified_checksums": verified,
        "authoritative_validator": "PASS",
    }


def verify_evidence(
    root: Path,
    *,
    run_id: str,
    source_commit: str,
    workflow_run_id: str | None = None,
) -> dict[str, Any]:
    """Verify the complete V2/V3 cross-evidence contract."""

    root = Path(root).resolve()

    require(
        isinstance(run_id, str)
        and RUN_ID_RE.fullmatch(run_id) is not None,
        "RUN_ID is invalid",
    )

    require(
        isinstance(source_commit, str)
        and COMMIT_RE.fullmatch(source_commit) is not None,
        "SOURCE_COMMIT must be a full lowercase Git SHA",
    )

    p3 = root / "P3"

    environment = read_json(
        p3 / "reports" / "environment.json",
        "Environment JSON",
    )

    require(
        environment.get("schema") == "qflpn-p3-environment-v1",
        "Environment schema mismatch",
    )

    require(
        environment.get("run_id") == run_id,
        "Environment RUN_ID mismatch",
    )

    repository = environment.get("repository")

    require(
        isinstance(repository, dict),
        "Environment repository metadata is missing",
    )

    require(
        repository.get("commit") == source_commit,
        "Environment source commit mismatch",
    )

    environment_workflow_id = environment.get(
        "workflow_run_id"
    )

    require(
        isinstance(environment_workflow_id, str)
        and WORKFLOW_ID_RE.fullmatch(environment_workflow_id) is not None,
        "Environment workflow_run_id is missing or invalid",
    )

    if workflow_run_id is not None:
        require(
            isinstance(workflow_run_id, str)
            and WORKFLOW_ID_RE.fullmatch(workflow_run_id) is not None,
            "Workflow run ID is invalid",
        )

        require(
            workflow_run_id == environment_workflow_id,
            "Environment workflow run ID mismatch",
        )

    else:
        workflow_run_id = environment_workflow_id

    v2_environment = environment.get("v2")
    v3_environment = environment.get("v3")

    require(
        isinstance(v2_environment, dict),
        "Environment V2 configuration is missing",
    )

    require(
        isinstance(v3_environment, dict),
        "Environment V3 configuration is missing",
    )

    v2_dimension = v2_environment.get("dimension")
    v3_dimension = v3_environment.get("dimension")

    require(
        isinstance(v2_dimension, int)
        and not isinstance(v2_dimension, bool)
        and v2_dimension > 0,
        "Environment V2 dimension is invalid",
    )

    require(
        isinstance(v3_dimension, int)
        and not isinstance(v3_dimension, bool)
        and v3_dimension > 0,
        "Environment V3 dimension is invalid",
    )

    v2 = verify_v2(
        root,
        run_id,
        workflow_run_id,
        source_commit,
    )

    require(
        v2["dimension"] == v2_dimension,
        "Environment and V2 benchmark dimensions differ",
    )

    v3 = verify_v3(
        root,
        run_id,
        source_commit,
        workflow_run_id,
    )

    v3_rows = read_csv(
        p3 / "benchmarks" / "benchmark_results_v3.csv",
        V3_REQUIRED,
    )

    v3_run_dimensions = {
        int(row["dimension"])
        for row in v3_rows
        if row.get("run_id") == run_id
    }

    require(
        v3_run_dimensions == {v3_dimension},
        "Environment and V3 benchmark dimensions differ",
    )

    return {
        "schema": "qflpn-p3-evidence-consistency-v2",
        "validation": "PASS",
        "run_id": run_id,
        "source_commit": source_commit,
        "workflow_run_id": workflow_run_id,
        "evidence": {
            "environment": "PASS",
            "execution_identity": "PASS",
            "benchmark_v2": "PASS",
            "v2_authoritative_validator": "PASS",
            "v2_checksums": "PASS",
            "benchmark_v3": "PASS",
            "v3_authoritative_validator": "PASS",
            "v3_persistent_report": "PASS",
            "v3_checksums": "PASS",
        },
        "benchmark_v2": v2,
        "benchmark_v3": v3,
    }


def atomic_write_json(
    path: Path,
    value: dict[str, Any],
) -> None:
    """Atomically write the final evidence-consistency JSON."""

    require(
        not path.is_symlink(),
        f"Output must not be a symlink: {path}",
    )

    path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    temporary: Path | None = None

    try:
        with tempfile.NamedTemporaryFile(
            mode="w",
            encoding="utf-8",
            newline="\n",
            dir=path.parent,
            prefix=f".{path.name}.",
            suffix=".tmp",
            delete=False,
        ) as stream:
            temporary = Path(stream.name)

            json.dump(
                value,
                stream,
                indent=2,
                ensure_ascii=False,
                allow_nan=False,
                sort_keys=True,
            )

            stream.write("\n")
            stream.flush()
            os.fsync(stream.fileno())

        os.replace(
            temporary,
            path,
        )

        temporary = None

    finally:
        if temporary is not None:
            temporary.unlink(missing_ok=True)


def main() -> int:
    parser = argparse.ArgumentParser(
        description=(
            "Cross-validate P3 V2 and V3 evidence for one "
            "RUN_ID, source commit and workflow run."
        )
    )

    parser.add_argument(
        "--root",
        type=Path,
        default=Path("."),
    )

    parser.add_argument(
        "--run-id",
        default=os.environ.get("P3_RUN_ID")
        or os.environ.get("RUN_ID"),
    )

    parser.add_argument(
        "--source-commit",
        default=os.environ.get("P3_SOURCE_COMMIT")
        or os.environ.get("SOURCE_COMMIT"),
    )

    parser.add_argument(
        "--workflow-run-id",
        default=os.environ.get("P3_WORKFLOW_RUN_ID")
        or os.environ.get("GITHUB_RUN_ID"),
    )

    parser.add_argument(
        "--json-output",
        type=Path,
        default=Path(
            "P3/reports/evidence-consistency.json"
        ),
    )

    args = parser.parse_args()

    try:
        require(
            isinstance(args.run_id, str) and bool(args.run_id),
            "--run-id, P3_RUN_ID or RUN_ID is required",
        )

        require(
            isinstance(args.source_commit, str)
            and bool(args.source_commit),
            "--source-commit, P3_SOURCE_COMMIT "
            "or SOURCE_COMMIT is required",
        )

        result = verify_evidence(
            args.root,
            run_id=args.run_id,
            source_commit=args.source_commit,
            workflow_run_id=args.workflow_run_id,
        )

        output_path = args.json_output

        if not output_path.is_absolute():
            output_path = Path.cwd() / output_path

        atomic_write_json(
            output_path,
            result,
        )

        print("P3_EVIDENCE_CONSISTENCY: PASS")
        print(f"P3_EVIDENCE_RUN_ID={args.run_id}")
        print(f"P3_EVIDENCE_SOURCE_COMMIT={args.source_commit}")
        print(
            "P3_EVIDENCE_WORKFLOW_RUN_ID="
            f"{result['workflow_run_id']}"
        )
        print(f"P3_EVIDENCE_REPORT={output_path}")

        return 0

    except (
        EvidenceError,
        OSError,
        ValueError,
        TypeError,
        KeyError,
    ) as exc:
        print(
            "P3_EVIDENCE_CONSISTENCY: FAIL: "
            f"{type(exc).__name__}: {exc}",
            file=sys.stderr,
        )

        return 1


if __name__ == "__main__":
    raise SystemExit(main())
